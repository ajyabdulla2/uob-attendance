import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:firebase_auth/firebase_auth.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/foundation.dart';
import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:shared_preferences/shared_preferences.dart';

import 'app.dart';
import 'core/config/app_config.dart';
import 'core/diagnostics/error_log.dart';
import 'core/theme/app_settings.dart';
import 'features/push/application/push_providers.dart';
import 'features/push/data/device_notifications.dart';
// Generated by `flutterfire configure` — git-ignored, never committed.
import 'firebase_options.dart';

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  // Uncaught errors go to «سجل الأخطاء» (profile) so users can send them.
  final previous = FlutterError.onError;
  FlutterError.onError = (details) {
    ErrorLog.record(details.exception, details.stack, details.library);
    previous?.call(details);
  };
  PlatformDispatcher.instance.onError = (error, stack) {
    ErrorLog.record(error, stack);
    return false;
  };
  final prefs = await SharedPreferences.getInstance();

  Object? startupError;
  try {
    await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
    if (AppConfig.useEmulator) {
      await FirebaseAuth.instance.useAuthEmulator(AppConfig.emulatorHost, AppConfig.authEmulatorPort);
      FirebaseFirestore.instance.useFirestoreEmulator(AppConfig.emulatorHost, AppConfig.firestoreEmulatorPort);
    }
    // Firestore's own cache complements the Drift outbox; on the web it is
    // off by default (admins use the web panel online).
    if (!kIsWeb) {
      FirebaseFirestore.instance.settings = const Settings(persistenceEnabled: true);
    }
  } catch (e) {
    startupError = e;
  }

  runApp(
    ProviderScope(
      overrides: [
        sharedPreferencesProvider.overrideWithValue(prefs),
        // Phone notifications (FCM + local reminders): Android only for now.
        if (startupError == null && !kIsWeb && defaultTargetPlatform == TargetPlatform.android)
          deviceNotificationsProvider.overrideWithValue(AndroidDeviceNotifications()),
      ],
      child: startupError == null ? const AttendanceApp() : ConfigErrorApp(error: startupError),
    ),
  );
}
